"""Dataclass models for the roster + substitute domain.

These are plain data holders. All business logic lives in the service layer
so the models stay easy to serialize and test.
"""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional

from .enums import (
    AuditAction,
    AvailabilityStatus,
    GameStatus,
    NotificationType,
    Position,
    RosterEntryStatus,
    RosterRole,
    SelectionSource,
    SlotStatus,
    SlotType,
    SubstituteStatus,
)


@dataclass
class Team:
    id: str
    name: str
    division: str = ""
    club_id: Optional[str] = None
    division_id: Optional[str] = None
    # Idempotency key for the CSV import (#93): the ``team_code`` a repeat
    # upload is matched against, so re-importing updates in place instead of
    # creating duplicates. None for teams created outside the import flow.
    external_ref: Optional[str] = None
    # Permanent owning program (#180/#233, formerly ``league_id``). A team is a
    # permanent member of one program; season-specific division participation
    # lives in SeasonTeamRegistration, not on the Team. Nullable — pre-#180 teams
    # are backfilled from their division's season program by migration 021, and a
    # team created without a division has none until one is derived/assigned.
    program_id: Optional[str] = None
    # Permanent owning League — the hard competition boundary (#283). A Team
    # belongs to exactly one League and may only register (per Season) into that
    # League. Nullable at the model level; migration 034 assigns a permanent
    # league_id to every existing Team (unambiguous mappings automatically; an
    # operator decision for Teams historically registered across multiple
    # Leagues). The invariant ``league.program_id == team.program_id`` (a Team's
    # League and Program agree) is enforced in the service layer.
    league_id: Optional[str] = None


@dataclass
class Player:
    id: str
    team_id: str
    # Flattened DISPLAY name — kept for every legacy consumer. When the
    # structured names below are set it is always derived ("<first> <last>",
    # see domain.identity.derive_display_name), never free-typed (#273).
    name: str
    position: Position
    shoots: Optional[str] = None
    jersey_number: Optional[int] = None
    is_active: bool = True
    # Idempotency key for the CSV import (#93): the ``player_code`` a repeat
    # upload is matched against. None for players created outside the import
    # flow.
    external_ref: Optional[str] = None
    # -- durable athlete identity (#273) --------------------------------
    # Structured names. Nullable: legacy players keep only the flattened
    # ``name`` until an edit/import supplies real parts — migration 058 never
    # guesses a first/last split from the display name.
    first_name: Optional[str] = None
    last_name: Optional[str] = None
    preferred_name: Optional[str] = None
    # PRIVATE birthdate, canonical "YYYY-MM-DD" (a calendar date, no
    # timezone). Stripped from every default facade payload — operators opt
    # in explicitly; ordinary Coach/public payloads never carry it (#273/#124
    # boundary).
    birthdate: Optional[str] = None
    # Stable governing-body registration number (private, same handling as
    # birthdate). The duplicate detector keys on it; it is never a merge key.
    registration_number: Optional[str] = None
    # Coach's 1-7 skill assessment (owner ruling on #287 assigns the field to
    # #273). None = unrated, a fully supported state substitute ranking must
    # degrade on, never exclude.
    skill_rating: Optional[int] = None
    # NOTE (#273): ``guardian_person_id`` is REMOVED from the model/contract.
    # It was serialized but never read or written by any service; the real,
    # verified guardian relationship is ``GuardianLink`` (#26/#35). The DB
    # column is left in place untouched (dropping it is a follow-up
    # migration), so existing rows and the 040 SQLite table rebuild are
    # unaffected.

    @property
    def slot_type(self) -> SlotType:
        return self.position.slot_type


@dataclass
class Game:
    id: str
    home_team_id: str
    start_time: datetime
    target_goalies: int = 1
    target_skaters: int = 15
    max_skaters: int = 18
    away_team_id: Optional[str] = None
    rink: Optional[str] = None
    end_time: Optional[datetime] = None
    roster_lock_time: Optional[datetime] = None
    locked: bool = False
    cancelled: bool = False
    published: bool = False
    season_id: Optional[str] = None
    division_id: Optional[str] = None
    ice_slot_id: Optional[str] = None
    # A draft game generated by the scheduler (#86): never public until it is
    # published (which clears this flag). Distinguishes generated drafts from
    # ordinary unpublished games.
    is_draft: bool = False
    # Owning competition league (#233 Slice C1b). Nullable; backfilled from the
    # game's division league by the reparent migration.
    league_id: Optional[str] = None
    # A Game's competition kind (#283 Slice D): "regular" (counts toward
    # standings, bound to one LeagueSeason — both teams registered in it) or
    # "exhibition" (a friendly that may cross League lines and never affects
    # standings; carries no owning League or Division). Stored as the plain
    # GameType enum string.
    game_type: str = "regular"
    # The exact LeagueSeason a REGULAR game belongs to (#283 Slice E) — its
    # single source of competition identity, so season_id and league_id can
    # never drift apart. NULL for exhibitions (which have no owning
    # LeagueSeason). Backfilled for existing regular games from their unique
    # (league_id, season_id) pair by migration 037.
    league_season_id: Optional[str] = None


